ON B.BRANCH_ID = C.BRANCH_ID
GROUP BY B.BRANCH_NAME, B.EMIRATE, B.CONCEPT , C.ORDER_CHANNEL,LEFT(C.BUSINESS_MONTH,4),RIGHT(C.BUSINESS_MONTH,2)
ORDER BY GROSS_MARGIN_PCT DESC;


