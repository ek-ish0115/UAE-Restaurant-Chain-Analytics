'''Analysis 1 — Overall business KPIs'''

SELECT 
    COUNT(DISTINCT ORDER_CHANNEL) AS Total_order_channel,
    SUM(ORDERS_COUNT) AS TOTAL_ORDERS,
    SUM(COVERS) AS TOTAL_CUSTOMERS,
    SUM(GROSS_SALES_AED) AS GROSS_SALES, 
    SUM(NET_SALES_AED) AS NET_SALES, 
    SUM(DISCOUNTS_AED) AS DISCOUNT, 
    SUM(NET_REVENUE_AED) AS NET_REVENUE,
    SUM(AGGREGATOR_COMMISSION_AED) AS COMMISSION,
    SUM(SERVICE_CHARGE_AED) AS TOTAL_SERVICE_CHARGE,
    SUM(VAT_AED) AS TOTAL_VAT,
    SUM(FOOD_COST_AED) AS TOTAL_FOOD_cOST,
    ROUND(AVG(AVG_PREP_MINUTES),2) AS AVG_PREP_MINUTE,
    ROUND(AVG(AVG_REVIEW_SCORE),2) AS AVG_RATING,
    ROUND(SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT),2) AS AOV,
    ROUND(SUM(FOOD_COST_AED)/SUM(NET_REVENUE_AED)*100,2) AS FOOD_COST_PCT,
    ROUND(SUM(AGGREGATOR_COMMISSION_AED)/SUM(GROSS_SALES_AED) *100,2) AS COMMISION_PCT,
    SUM(NET_REVENUE_AED) - SUM(FOOD_COST_AED) AS GROSS_MARGIN,
    ROUND((SUM(NET_REVENUE_AED) - SUM(FOOD_COST_AED))/SUM(NET_REVENUE_AED) *100,2) AS GROSS_MARGIN_PCT
    
FROM CHANNEL_DAILY;

'''Monthly orders KPI'''

SELECT 
    BUSINESS_MONTH,
    COUNT(DISTINCT ORDER_CHANNEL) AS Total_order_channel,
    SUM(ORDERS_COUNT) AS TOTAL_ORDERS,
    LAG(SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH) AS PREV_MONTH_ORDER,
    ROUND((SUM(ORDERS_COUNT) - LAG(SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH))/LAG(SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH) *100,2) AS         MOM_ORDER_GROWTH_PCT,
    SUM(COVERS) AS TOTAL_CUSTOMERS,
    LAG(SUM(COVERS)) OVER(ORDER BY BUSINESS_MONTH) AS Prev_month_cust,
    ROUND((SUM(COVERS)- LAG(SUM(COVERS)) OVER(ORDER BY BUSINESS_MONTH))/LAG(SUM(COVERS)) OVER(ORDER BY BUSINESS_MONTH) *100,2) AS MOM_CUST_GROWTH_PCT,
    SUM(GROSS_SALES_AED) AS GROSS_SALES, 
    SUM(NET_SALES_AED) AS NET_SALES, 
    SUM(DISCOUNTS_AED) AS DISCOUNT, 
    SUM(NET_REVENUE_AED) AS NET_REVENUE,
    LAG(SUM(NET_REVENUE_AED)) OVER(ORDER BY BUSINESS_MONTH) AS Prev_month_NET_REVENUE,
    ROUND((SUM(NET_REVENUE_AED)-LAG(SUM(NET_REVENUE_AED)) OVER(ORDER BY BUSINESS_MONTH))/LAG(SUM(NET_REVENUE_AED)) OVER(ORDER BY BUSINESS_MONTH) * 100,2) AS MOM_REVENUE_GROWTH_PCT,
    SUM(AGGREGATOR_COMMISSION_AED) AS COMMISSION,
    SUM(SERVICE_CHARGE_AED) AS TOTAL_SERVICE_CHARGE,
    SUM(VAT_AED) AS TOTAL_VAT,
    SUM(FOOD_COST_AED) AS TOTAL_FOOD_cOST,
    AVG(AVG_PREP_MINUTES) AS AVG_PREP_MINUTE,
    AVG(AVG_REVIEW_SCORE) AS AVG_RATING,
    SUM(FOOD_COST_AED) AS MONTHLY_FOOD_COST,
    SUM(DISCOUNTS_AED) AS MONTHLY_DISCOUNTS,
    SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT) AS MONTHLY_AOV,
    LAG(SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH) AS PREV_MONTH_AOV,
    ROUND(
    ((SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT))-
    (LAG(SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH)))/
    (LAG(SUM(NET_REVENUE_AED)/SUM(ORDERS_COUNT)) OVER(ORDER BY BUSINESS_MONTH)) * 100,2) MOM_AOV_GROWTH_PCT
FROM CHANNEL_DAILY
GROUP BY BUSINESS_MONTH
ORDER BY BUSINESS_MONTH;



