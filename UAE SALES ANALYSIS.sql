SELECT BUSINESS_MONTH,NET_SALES FROM (
    SELECT BUSINESS_MONTH,
        LEFT(BUSINESS_MONTH, 4) AS YEAR_,
        SUM(NET_SALES_AED) AS NET_SALES,
        RANK() OVER(PARTITION BY  LEFT(BUSINESS_MONTH, 4) ORDER BY SUM(NET_REVENUE_AED) DESC) AS REVENUE_RANK
        
    FROM CHANNEL_DAILY
