SELECT ORDER_CHANNEL, LEFT(BUSINESS_MONTH,4) AS YEAR_, RIGHT(BUSINESS_MONTH,2) AS MONTH_,
    SUM(NET_REVENUE_AED) AS NET_REVENUE,
    LAG(SUM(NET_REVENUE_AED)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH) AS Prev_month_revenue,
    ROUND((SUM(NET_REVENUE_AED)-LAG(SUM(NET_REVENUE_AED)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH))/LAG(SUM(NET_REVENUE_AED)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH) * 100,2) AS MOM_REVENUE_GROWTH_PCT,
    SUM(ORDERS_COUNT) AS TOTAL_ORDERS,
    LAG(SUM(ORDERS_COUNT)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH) AS Prev_month_Orders,
    ROUND((SUM(ORDERS_COUNT)-LAG(SUM(ORDERS_COUNT)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH))/LAG(SUM(ORDERS_COUNT)) OVER(PARTITION BY ORDER_CHANNEL ORDER BY BUSINESS_MONTH) * 100,2) AS MOM_ORDER_GROWTH_PCT

